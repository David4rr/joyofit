package com.joyodigitama.huaweiwear

import androidx.health.connect.client.records.ExerciseSessionRecord as Ex

/**
 * Huawei sport type (the type byte of the workout summary) to a Health Connect `EXERCISE_TYPE_*`.
 * The numbers are `HuaweiWorkoutGbParser.HuaweiActivityType` of Gadgetbridge; sports Health Connect
 * has no type for become `EXERCISE_TYPE_OTHER_WORKOUT`.
 */
internal object HealthConnectExercise {
  fun type(huaweiType: Int): Int = when (huaweiType and 0xFF) {
    1, 11 -> Ex.EXERCISE_TYPE_RUNNING
    2 -> Ex.EXERCISE_TYPE_WALKING
    3, 213 -> Ex.EXERCISE_TYPE_BIKING
    4, 14 -> Ex.EXERCISE_TYPE_HIKING
    5 -> Ex.EXERCISE_TYPE_RUNNING_TREADMILL
    6 -> Ex.EXERCISE_TYPE_SWIMMING_POOL
    7, 141 -> Ex.EXERCISE_TYPE_BIKING_STATIONARY
    8 -> Ex.EXERCISE_TYPE_SWIMMING_OPEN_WATER
    13 -> Ex.EXERCISE_TYPE_WALKING
    25 -> Ex.EXERCISE_TYPE_SCUBA_DIVING
    128 -> Ex.EXERCISE_TYPE_TABLE_TENNIS
    129, 181 -> Ex.EXERCISE_TYPE_BADMINTON
    130 -> Ex.EXERCISE_TYPE_TENNIS
    131, 187 -> Ex.EXERCISE_TYPE_SOCCER
    132 -> Ex.EXERCISE_TYPE_BASKETBALL
    133, 188 -> Ex.EXERCISE_TYPE_VOLLEYBALL
    134, 142 -> Ex.EXERCISE_TYPE_ELLIPTICAL
    135 -> Ex.EXERCISE_TYPE_ROWING_MACHINE
    136 -> Ex.EXERCISE_TYPE_STAIR_CLIMBING_MACHINE
    137 -> Ex.EXERCISE_TYPE_YOGA
    138 -> Ex.EXERCISE_TYPE_PILATES
    139 -> Ex.EXERCISE_TYPE_EXERCISE_CLASS
    140 -> Ex.EXERCISE_TYPE_STRENGTH_TRAINING
    143 -> Ex.EXERCISE_TYPE_HIGH_INTENSITY_INTERVAL_TRAINING
    145, 146, 147, 157 -> Ex.EXERCISE_TYPE_CALISTHENICS
    148, 151, 159, 164, 166 -> Ex.EXERCISE_TYPE_MARTIAL_ARTS
    149, 150, 158 -> Ex.EXERCISE_TYPE_BOXING
    152 -> Ex.EXERCISE_TYPE_FENCING
    153, 154, 155, 156, 162, 165, 167 -> Ex.EXERCISE_TYPE_DANCING
    160, 161 -> Ex.EXERCISE_TYPE_GYMNASTICS
    163 -> Ex.EXERCISE_TYPE_ROLLER_HOCKEY
    169 -> Ex.EXERCISE_TYPE_FRISBEE_DISC
    177 -> Ex.EXERCISE_TYPE_STAIR_CLIMBING
    182 -> Ex.EXERCISE_TYPE_HANDBALL
    183 -> Ex.EXERCISE_TYPE_BASEBALL
    184 -> Ex.EXERCISE_TYPE_SOFTBALL
    185 -> Ex.EXERCISE_TYPE_CRICKET
    186 -> Ex.EXERCISE_TYPE_RUGBY
    204 -> Ex.EXERCISE_TYPE_ICE_HOCKEY
    191 -> Ex.EXERCISE_TYPE_SQUASH
    194 -> Ex.EXERCISE_TYPE_SAILING
    195 -> Ex.EXERCISE_TYPE_SURFING
    197, 198, 199, 202 -> Ex.EXERCISE_TYPE_PADDLING
    200 -> Ex.EXERCISE_TYPE_ROWING
    203 -> Ex.EXERCISE_TYPE_ICE_SKATING
    209 -> Ex.EXERCISE_TYPE_SKATING
    210 -> Ex.EXERCISE_TYPE_ROCK_CLIMBING
    215 -> Ex.EXERCISE_TYPE_PARAGLIDING
    else -> Ex.EXERCISE_TYPE_OTHER_WORKOUT
  }
}
