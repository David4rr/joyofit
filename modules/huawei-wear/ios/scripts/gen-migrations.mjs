// Regenerates ios/WearMigrations.swift from modules/huawei-wear/schema/joyofit-db-migrations.json.
//
//   node modules/huawei-wear/ios/scripts/gen-migrations.mjs
//
// The JSON is the one source of truth: JS imports it (src/db/migrations.ts) and the Android module reads it as an asset. CocoaPods cannot
// ship a file from outside the pod directory and the Linux pipeline copies resource bundles with `cp -R`, so the iOS module compiles the
// same text into a Swift string instead. ModuleLogicTests fails when this file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '..', '..', 'schema', 'joyofit-db-migrations.json');
const target = join(here, '..', 'WearMigrations.swift');
const json = readFileSync(source, 'utf8').trimEnd();
if (json.includes('"""#')) throw new Error('the migrations JSON contains the Swift raw string terminator');
writeFileSync(
  target,
  `// GENERATED by ios/scripts/gen-migrations.mjs from modules/huawei-wear/schema/joyofit-db-migrations.json. Do not edit.
// Entry \`i\` upgrades \`PRAGMA user_version\` i to i + 1, as in src/db/migrations.ts and the Android SyncStore.
enum WearMigrations {
    static let json = #"""
${json}
"""#
}
`,
);
console.log(`wrote ${target}`);
